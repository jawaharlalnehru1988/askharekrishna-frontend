export interface PrefixOption {
    prefix: string;
    count: number;
}

export function getAvailablePrefixes(length: 1 | 2 | 3, names: BabyNameItem[]): PrefixOption[] {
    const map = new Map<string, number>();
    for (const item of names) {
        let key = '';
        if (length === 1) key = item.char1.toUpperCase();
        else if (length === 2) key = item.char2;
        else if (length === 3) key = item.char3;

        if (key) {
            map.set(key, (map.get(key) || 0) + 1);
        }
    }
    return Array.from(map.entries())
        .map(([prefix, count]) => ({ prefix, count }))
        .sort((a, b) => a.prefix.localeCompare(b.prefix));
}

